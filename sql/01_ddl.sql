DROP VIEW IF EXISTS vw_usuario_detalhes;

DROP TABLE IF EXISTS
    avalia,
    visualizacao,
    atua,
    pertence_a,
    filme,
    pessoa,
    genero,
    perfil,
    assinatura,
    usuario,
    plano
CASCADE;

-- 1. Tabela Plano
CREATE TABLE plano (
    id_plano      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL UNIQUE,
    preco_mensal  NUMERIC(10, 2) NOT NULL CHECK (preco_mensal > 0),
    max_telas     INTEGER NOT NULL CHECK (max_telas >= 1),
    qualidade_max VARCHAR(20) NOT NULL CHECK (qualidade_max IN ('HD', 'Full HD', '4K'))
);

-- 2. Tabela Usuario (idade é atributo derivado calculado na view vw_usuario_detalhes)
CREATE TABLE usuario (
    id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE CHECK (POSITION('@' IN email) > 1),
    cpf             VARCHAR(14) NOT NULL UNIQUE CHECK (cpf ~ '^[0-9]{3}\.[0-9]{3}\.[0-9]{3}-[0-9]{2}$'),
    senha           VARCHAR(255) NOT NULL,
    data_nascimento DATE NOT NULL,
    data_cadastro   DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_usuario_datas CHECK (data_cadastro >= data_nascimento)
);

-- 3. Tabela Assinatura (relacionamentos Contrata 1:N e Refere-se_a 1:N)
CREATE TABLE assinatura (
    id_assinatura INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_plano      INTEGER NOT NULL REFERENCES plano(id_plano) ON DELETE RESTRICT ON UPDATE CASCADE,
    data_inicio   DATE NOT NULL DEFAULT CURRENT_DATE,
    data_fim      DATE NULL,
    situacao      VARCHAR(20) NOT NULL DEFAULT 'Ativa' CHECK (situacao IN ('Ativa', 'Cancelada', 'Suspensa')),
    CONSTRAINT ck_assinatura_vigencia CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- 4. Tabela Perfil (relacionamento Possui 1:N com participação total de ambos os lados)
CREATE TABLE perfil (
    id_perfil         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
    nome              VARCHAR(80) NOT NULL,
    infantil          BOOLEAN NOT NULL DEFAULT FALSE,
    classificacao_max VARCHAR(5) NOT NULL DEFAULT '18' CHECK (classificacao_max IN ('L', '10', '12', '14', '16', '18')),
    avatar_color      VARCHAR(20) NOT NULL DEFAULT 'red' CHECK (avatar_color IN ('red', 'amber', 'teal', 'cobalt', 'emerald', 'zinc')),
    CONSTRAINT ck_perfil_infantil_class CHECK (NOT infantil OR classificacao_max IN ('L', '10', '12'))
);

-- 5. Tabela Genero
CREATE TABLE genero (
    id_genero INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(80) NOT NULL UNIQUE,
    descricao TEXT NOT NULL
);

-- 6. Tabela Pessoa (profissionais do audiovisual: diretores, atores e atrizes)
CREATE TABLE pessoa (
    id_pessoa       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    data_nascimento DATE NOT NULL,
    nacionalidade   VARCHAR(80) NOT NULL
);

-- 7. Tabela Filme (relacionamento Direcao 1:N via FK id_diretor obrigatória)
CREATE TABLE filme (
    id_filme        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo          VARCHAR(200) NOT NULL,
    titulo_original VARCHAR(200) NOT NULL,
    ano_lancamento  INTEGER NOT NULL CHECK (ano_lancamento BETWEEN 1895 AND 2035),
    sinopse         TEXT NOT NULL,
    duracao_min     INTEGER NOT NULL CHECK (duracao_min > 0),
    classificacao   VARCHAR(5) NOT NULL CHECK (classificacao IN ('L', '10', '12', '14', '16', '18')),
    data_inclusao   DATE NOT NULL DEFAULT CURRENT_DATE,
    id_diretor      INTEGER NOT NULL REFERENCES pessoa(id_pessoa) ON DELETE RESTRICT ON UPDATE CASCADE,
    capa_url        VARCHAR(500) NOT NULL DEFAULT '',
    capa_tema       VARCHAR(20) NOT NULL DEFAULT 'noir' CHECK (capa_tema IN ('noir', 'amber', 'cyan', 'emerald', 'crimson', 'slate'))
);

-- 8. Tabela Associativa Pertence_a (relacionamento N:M Filme <-> Genero)
CREATE TABLE pertence_a (
    id_filme  INTEGER NOT NULL REFERENCES filme(id_filme) ON DELETE CASCADE ON UPDATE CASCADE,
    id_genero INTEGER NOT NULL REFERENCES genero(id_genero) ON DELETE RESTRICT ON UPDATE CASCADE,
    PRIMARY KEY (id_filme, id_genero)
);

-- 9. Tabela Associativa Atua (relacionamento N:M Pessoa <-> Filme com atributos próprios)
CREATE TABLE atua (
    id_atua    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa  INTEGER NOT NULL REFERENCES pessoa(id_pessoa) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_filme   INTEGER NOT NULL REFERENCES filme(id_filme) ON DELETE RESTRICT ON UPDATE CASCADE,
    funcao     VARCHAR(80) NOT NULL,
    personagem VARCHAR(150) NOT NULL,
    CONSTRAINT uq_atua_pessoa_filme_personagem UNIQUE (id_pessoa, id_filme, personagem)
);

-- 10. Tabela Visualizacao (relacionamentos Realiza 1:N e Exibido_em 1:N)
CREATE TABLE visualizacao (
    id_visualizacao    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_perfil          INTEGER NOT NULL REFERENCES perfil(id_perfil) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_filme           INTEGER NOT NULL REFERENCES filme(id_filme) ON DELETE RESTRICT ON UPDATE CASCADE,
    data_hora_inicio   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    minutos_assistidos INTEGER NOT NULL CHECK (minutos_assistidos > 0),
    conclusao          BOOLEAN NOT NULL DEFAULT FALSE
);

-- 11. Tabela Associativa Avalia (relacionamento N:M Perfil <-> Filme com atributos próprios)
CREATE TABLE avalia (
    id_perfil      INTEGER NOT NULL REFERENCES perfil(id_perfil) ON DELETE RESTRICT ON UPDATE CASCADE,
    id_filme       INTEGER NOT NULL REFERENCES filme(id_filme) ON DELETE RESTRICT ON UPDATE CASCADE,
    nota           INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
    data_avaliacao DATE NOT NULL DEFAULT CURRENT_DATE,
    comentario     TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (id_perfil, id_filme)
);

-- Visão para expor o atributo derivado "idade" de Usuario
CREATE VIEW vw_usuario_detalhes AS
SELECT
    u.id_usuario,
    u.nome,
    u.email,
    u.cpf,
    u.senha,
    u.data_nascimento,
    u.data_cadastro,
    EXTRACT(YEAR FROM AGE(CURRENT_DATE, u.data_nascimento))::INTEGER AS idade
FROM usuario u;

-- Índices em chaves estrangeiras para otimizar junções e verificações referenciais
CREATE INDEX idx_assinatura_usuario  ON assinatura(id_usuario);
CREATE INDEX idx_assinatura_plano    ON assinatura(id_plano);
CREATE INDEX idx_perfil_usuario      ON perfil(id_usuario);
CREATE INDEX idx_filme_diretor       ON filme(id_diretor);
CREATE INDEX idx_pertence_a_genero   ON pertence_a(id_genero);
CREATE INDEX idx_atua_pessoa         ON atua(id_pessoa);
CREATE INDEX idx_atua_filme          ON atua(id_filme);
CREATE INDEX idx_visualizacao_perfil ON visualizacao(id_perfil);
CREATE INDEX idx_visualizacao_filme  ON visualizacao(id_filme);
CREATE INDEX idx_avalia_filme        ON avalia(id_filme);
